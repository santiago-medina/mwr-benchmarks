#!/usr/bin/env python3
"""Write tests/servo_paths.rs: one `use` per js:: path Servo aac43a3 imports.

The input, tools/servo_aac43a3_js_paths.tsv (`<files>\t<path>`), is the
survey of components/script and components/script_bindings in
SERVO_BINDINGS.md. If the facade drops or renames an item Servo imports,
this test stops compiling.
"""
from pathlib import Path

here = Path(__file__).resolve().parent
paths = []
for line in (here / "servo_aac43a3_js_paths.tsv").read_text().splitlines():
    path = line.split("\t")[1]
    if path.endswith("::self") or path == "self":
        path = path[: -len("::self")] if path.endswith("::self") else ""
    if path and path not in paths:
        paths.append(path)
out = [
    "//! Generated by tools/gen_path_test.py: every js:: path Servo aac43a3 imports",
    "//! must resolve in the facade (MOZJS_FACADE.md, milestone C0).",
    "#![allow(unused_imports, deprecated)]",
    "",
]
out += ["use mozjs::%s as _;" % p for p in sorted(paths)]
out += ["", "#[test]", "fn servo_import_paths_resolve() {", "    // Compiling this file is the test.", "}", ""]
(here.parent / "tests" / "servo_paths.rs").write_text("\n".join(out))
print("%d paths" % len(paths))

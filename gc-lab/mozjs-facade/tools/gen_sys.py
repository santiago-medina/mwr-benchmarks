#!/usr/bin/env python3
"""Turn mozjs_sys's bindgen output into facade definitions (MOZJS_FACADE.md).

Input: jsapi.rs and gluebindings.rs from the prebuilt mozjs_sys 153.3.0-1
archive (libmozjs-x86_64-unknown-linux-gnu.tar.gz). Type definitions are kept
byte for byte, so Servo's generated code sees the same structs and layouts.
Each `extern "C"` declaration becomes a Rust definition whose body reports
the entry point as unimplemented; each extern static becomes a zeroed
static with bindgen's mutability (`extern const` stays immutable, so Servo can
take `&ProxyClassOps` in a static initializer). Variadic tails are dropped (listed in the summary).

Entry points named in tools/implemented.txt delegate instead to the
hand-written `crate::sys::imp::<name>` with the same arguments; the bindgen
signature stays the authority, so a mismatched implementation fails to compile.

Usage: gen_sys.py <bindings dir> <output dir>
"""
import re
import sys
from pathlib import Path

HEADER = (
    "/* This Source Code Form is subject to the terms of the Mozilla Public\n"
    " * License, v. 2.0. If a copy of the MPL was not distributed with this\n"
    " * file, You can obtain one at http://mozilla.org/MPL/2.0/. */\n\n"
    "// Generated by mozjs-facade/tools/gen_sys.py from mozjs_sys 153.3.0-1\n"
    "// bindgen output. Do not edit: change the generator instead.\n\n"
)

FN = re.compile(r"^(\s*)pub fn ([A-Za-z0-9_]+)\s*\(", re.S)
# `extern const` statics whose types hold raw pointers are not Sync, so they
# must stay `static mut` (list produced by compiling; one name per line).
NONSYNC = set((Path(__file__).resolve().parent / "nonsync_statics.txt").read_text().split())
IMPLEMENTED = set((Path(__file__).resolve().parent / "implemented.txt").read_text().split())
# Statics with a real value: the constant Value handles point at fixed cells,
# as SpiderMonkey's do (jsapi.cpp `JS::UndefinedHandleValue` and friends).
STATIC_INIT = {
    name: "root::JS::Handle { _phantom_0: ::std::marker::PhantomData, ptr: &crate::sys::jsval::%s }" % target
    for name, target in (
        ("NullHandleValue", "NULL_HANDLE_TARGET"),
        ("UndefinedHandleValue", "UNDEFINED_HANDLE_TARGET"),
        ("TrueHandleValue", "TRUE_HANDLE_TARGET"),
        ("FalseHandleValue", "FALSE_HANDLE_TARGET"),
    )
}
STATIC = re.compile(r"^(\s*)pub static (mut )?([A-Za-z0-9_]+)\s*:\s*(.*);\s*$", re.S)


def convert(text, stats):
    out = []
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if stripped in ('extern "C" {', 'unsafe extern "C" {'):
            indent = line[: len(line) - len(line.lstrip())]
            i += 1
            item = []
            while True:
                cur = lines[i]
                if cur.strip() == "}" and cur.startswith(indent + "}"):
                    break
                item.append(cur)
                if cur.rstrip().endswith(";"):
                    out.extend(emit(item, stats))
                    item = []
                i += 1
            if item and any(x.strip() for x in item):
                raise SystemExit("dangling extern item: %r" % item)
            i += 1
            continue
        out.append(line)
        i += 1
    return "\n".join(out)


def emit(item, stats):
    attrs = [x for x in item if x.strip().startswith("#[")]
    body = [x for x in item if not x.strip().startswith("#[")]
    keep = [a for a in attrs if not a.strip().startswith("#[link_name")]
    decl = "\n".join(body)
    m = FN.match(decl)
    if m:
        name = m.group(2)
        if re.search(r"^\s*\.\.\.,?\s*$", decl, re.M):
            decl = re.sub(r"^\s*\.\.\.,?\s*\n", "", decl, flags=re.M)
            stats["variadic"].append(name)
        decl = decl.replace("pub fn ", "pub unsafe extern \"C\" fn ", 1)
        if name in IMPLEMENTED:
            if name in stats["seen"]:
                raise SystemExit("implemented name is ambiguous: " + name)
            call = "crate::sys::imp::%s(%s)" % (name, ", ".join(param_names(decl)))
            stats["implemented"] += 1
        else:
            call = "crate::sys::unimplemented_entry(\"" + name + "\")"
        stats["seen"].add(name)
        decl = decl.rstrip()[:-1] + " {\n" + m.group(1) + "    " + call + "\n" + m.group(1) + "}"
        stats["fn"] += 1
        return keep + [decl]
    m = STATIC.match(decl)
    if m:
        stats["static"] += 1
        init = STATIC_INIT.get(m.group(3), "unsafe { ::core::mem::zeroed() }")
        return keep + [
            "%spub static %s%s: %s = %s;"
            % (m.group(1), "mut " if m.group(2) or m.group(3) in NONSYNC else "", m.group(3), m.group(4), init)
        ]
    raise SystemExit("unknown extern item: %r" % decl)


def param_names(decl):
    """Parameter names of a bindgen `fn` declaration (types may hold commas)."""
    inner = decl[decl.index("(") + 1:]
    depth, cur, params = 0, "", []
    for i, ch in enumerate(inner):
        if ch == ">" and inner[i - 1] == "-":
            pass  # `->` in a function pointer type
        elif ch in "(<[":
            depth += 1
        elif ch in ")>]":
            if depth == 0:
                break
            depth -= 1
        if ch == "," and depth == 0:
            params.append(cur)
            cur = ""
        else:
            cur += ch
    params.append(cur)
    return [p.split(":")[0].strip() for p in params if p.strip()]


def main():
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    dst.mkdir(parents=True, exist_ok=True)
    seen = set()
    for name in ("jsapi.rs", "gluebindings.rs"):
        stats = {"fn": 0, "static": 0, "variadic": [], "implemented": 0, "seen": seen}
        # mozjs_sys modules live under crate::sys in the facade.
        text = convert((src / name).read_text().replace("crate::", "crate::sys::")
            .replace("pub type FILE = ::libc::FILE;", "pub type FILE = ::core::ffi::c_void;"), stats)
        (dst / name).write_text(HEADER + text)
        print("%s: %d functions (%d implemented), %d statics, variadic tails dropped: %s"
              % (name, stats["fn"], stats["implemented"], stats["static"], " ".join(stats["variadic"]) or "none"))
    missing = IMPLEMENTED - seen
    if missing:
        raise SystemExit("implemented.txt names no entry point: " + " ".join(sorted(missing)))


if __name__ == "__main__":
    main()

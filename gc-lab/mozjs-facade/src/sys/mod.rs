//! The `mozjs_sys` layer of the facade (MOZJS_FACADE.md).
//!
//! In mozjs this is a separate crate that links SpiderMonkey. Here it keeps
//! the same Rust items: the bindgen types are copied from mozjs_sys 153.3.0-1
//! so layouts match, and every C++ entry point becomes a Rust definition
//! that is implemented over the gc-lab engine one by one.

// The jsimpls module just implements traits so can be private
mod jsimpls;

// Modules with public definitions
pub mod glue;
pub mod jsgc;
pub mod jsid;
pub mod jsval;
pub mod trace;

// Reexport the bindings in the jsapi module
pub mod jsapi {
    pub use super::generated::root::*;

    /// `JS::SetGCZeal` only exists in SpiderMonkey debug builds (JS_GC_ZEAL),
    /// so the release bindgen output lacks it; Servo imports it under
    /// `debugmozjs`. Same signature as jsapi.h.
    pub unsafe extern "C" fn SetGCZeal(_cx: *mut JSContext, _zeal: u8, _frequency: u32) {
        super::unimplemented_entry("SetGCZeal")
    }
}

// The bindings generated by bindgen
#[doc(hidden)]
#[allow(
    dead_code,
    unused_variables,
    unpredictable_function_pointer_comparisons,
    clippy::all
)]
mod generated {
    #![allow(unnecessary_transmutes)]
    include!("generated/jsapi.rs");
}

/// Body of every SpiderMonkey entry point the facade does not implement yet.
///
/// Reaching it is a facade gap, not an engine error: the name says which
/// entry point to implement next.
#[cold]
#[track_caller]
pub fn unimplemented_entry(name: &str) -> ! {
    panic!("mozjs facade: {name} is not implemented yet")
}

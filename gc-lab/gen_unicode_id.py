#!/usr/bin/env python3
"""Usage: python3 -I gen_unicode_id.py DerivedCoreProperties.txt OUT.rs : emit ID_Start/ID_Continue range tables."""
import sys,re
props={'ID_Start':[], 'ID_Continue':[]}
ver=''
for line in open(sys.argv[1],encoding='utf-8'):
    if not ver and line.startswith('# DerivedCoreProperties-'): ver=line.strip()[2:]
    m=re.match(r'([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)\s*#',line)
    if m and m.group(3) in props:
        a=int(m.group(1),16); b=int(m.group(2) or m.group(1),16); props[m.group(3)].append((a,b))
def merge(r):
    r.sort(); out=[]
    for a,b in r:
        if out and a<=out[-1][1]+1: out[-1]=(out[-1][0],max(b,out[-1][1]))
        else: out.append((a,b))
    return [x for x in out if x[1]>=0x80]  # ASCII handled inline
with open(sys.argv[2],'w') as o:
    o.write(f'//! Generated by gen_unicode_id.py from {ver} (ID_Start, ID_Continue; non-ASCII ranges).\n')
    for k,name in (('ID_Start','ID_START'),('ID_Continue','ID_CONTINUE')):
        rs=merge(props[k]); o.write(f'#[rustfmt::skip]\npub(super) const {name}: &[(u32, u32)] = &[\n')
        for i in range(0,len(rs),6): o.write('    '+' '.join(f'(0x{a:X}, 0x{b:X}),' for a,b in rs[i:i+6])+'\n')
        o.write('];\n')
print(ver,{k:len(merge(v)) for k,v in props.items()})

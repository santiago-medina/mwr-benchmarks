#!/usr/bin/env python3
"""Usage: python3 -I gen_unicode_norm.py UCD_DIR OUT.rs
Emit the Unicode Normalization (UAX #15) tables for String.prototype.normalize:
canonical combining classes, full canonical and compatibility decompositions (already
recursive) and the canonical composition pairs (minus Full_Composition_Exclusion).
Hangul syllables are algorithmic (UAX #15 / Unicode §3.12) and not in the tables."""
import sys, os, re
D, OUT = sys.argv[1], sys.argv[2]
ver = open(os.path.join(D, 'DerivedNormalizationProps.txt'), encoding='utf-8').readline().strip()[2:]
ccc, canon, compat = {}, {}, {}
first = None
for line in open(os.path.join(D, 'UnicodeData.txt'), encoding='utf-8'):
    f = line.split(';')
    cp = int(f[0], 16)
    if f[3] != '0':
        ccc[cp] = int(f[3])
    if f[5]:
        parts = f[5].split()
        if parts[0].startswith('<'):
            compat[cp] = [int(x, 16) for x in parts[1:]]
        else:
            canon[cp] = [int(x, 16) for x in parts]
exclusions = set()
RX = re.compile(r'^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*Full_Composition_Exclusion\b')
for line in open(os.path.join(D, 'DerivedNormalizationProps.txt'), encoding='utf-8'):
    m = RX.match(line)
    if m:
        a = int(m.group(1), 16); b = int(m.group(2) or m.group(1), 16)
        exclusions.update(range(a, b + 1))
def full(cp, use_compat):
    d = canon.get(cp) or (compat.get(cp) if use_compat else None)
    if d is None:
        return [cp]
    return [x for c in d for x in full(c, use_compat)]
canon_full = {cp: full(cp, False) for cp in canon}
compat_full = {}
for cp in set(canon) | set(compat):
    d = full(cp, True)
    if d != canon_full.get(cp, [cp]):
        compat_full[cp] = d
pairs = sorted((d[0], d[1], cp) for cp, d in canon.items() if len(d) == 2 and cp not in exclusions)
runs = []
for cp in sorted(ccc):
    if runs and runs[-1][1] == cp - 1 and runs[-1][2] == ccc[cp]:
        runs[-1][1] = cp
    else:
        runs.append([cp, cp, ccc[cp]])
def table(name, m):
    data, rows = [], []
    for cp in sorted(m):
        rows.append(f'(0x{cp:X},{len(data)},{len(m[cp])})')
        data.extend(m[cp])
    out = [f'#[rustfmt::skip]\npub(super) static {name}: &[(u32, u16, u8)] = &[' + ','.join(rows) + '];']
    out.append(f'#[rustfmt::skip]\npub(super) static {name}_DATA: &[u32] = &[' + ','.join(f'0x{x:X}' for x in data) + '];')
    assert len(data) < 65536
    return '\n'.join(out)
with open(OUT, 'w', encoding='utf-8') as o:
    o.write(f'//! Generated by gen_unicode_norm.py from {ver} and UnicodeData.txt. Do not edit.\n')
    o.write('#[rustfmt::skip]\npub(super) static CCC: &[(u32, u32, u8)] = &[' + ','.join(f'(0x{a:X},0x{b:X},{c})' for a, b, c in runs) + '];\n')
    o.write(table('CANONICAL', canon_full) + '\n')
    o.write(table('COMPATIBILITY', compat_full) + '\n')
    o.write('#[rustfmt::skip]\npub(super) static COMPOSE: &[(u32, u32, u32)] = &[' + ','.join(f'(0x{a:X},0x{b:X},0x{c:X})' for a, b, c in pairs) + '];\n')
print(ver, 'ccc runs', len(runs), 'canonical', len(canon_full), 'compat', len(compat_full), 'pairs', len(pairs))
